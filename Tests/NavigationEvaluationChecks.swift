import Foundation

/// Produces an evidence report from actual engine runs; synthetic expectations never become field results.
enum NavigationEvaluationChecks {
    static func run(resources: URL, output: URL?) throws {
        try NavigationVerificationChecks.run(resources: resources, output: output)
        let graph = try CampusGraph.load(resources.appending(path: "CampusData/boyd_library_graph.json"))
        let geojson = try CampusGraph.load(resources.appending(path: "CampusData/boyd_library_graph.geojson"))
        precondition(graph.edges.count == geojson.edges.count)
        let route = try RoutePlanner.plan(graph: graph, from: "trace-0", to: "trace-7")
        let start = Date(timeIntervalSince1970: 1_700_000_000)
        let geometry = SimulationRoute(url: resources.appending(path: "Routes/boyd_to_library.geojson"))!
        var lines = [
            "# Navigation evaluation — software runs", "",
            "Generated by production-model checks. Synthetic runs test algorithms, not campus accessibility or travel safety.",
            "", "| Scenario | Accepted | Rejected | Departures | Rejoins | Turns | Arrivals |",
            "| --- | ---: | ---: | ---: | ---: | ---: | ---: |",
        ]
        for scenario in WalkScenario.allCases {
            var session = try NavigationSession(graph: graph, route: route, source: .simulation, started: start)
            for i in 0...Int((geometry.length + 80) / 0.7) {
                let sample = geometry.sample(i, scenario)
                let time = start.addingTimeInterval(Double(i) * 0.5)
                session.receive(
                    NavigationPosition(
                        time: time,
                        coordinate: MapCoordinate(
                            latitude: sample.position.coordinate.latitude,
                            longitude: sample.position.coordinate.longitude), accuracy: 1, source: .simulation),
                    now: time)
            }
            let kinds = session.events.map(\.kind)
            let departures = kinds.filter { $0 == .offRoute }.count
            let rejoins = kinds.filter { $0 == .rejoined }.count
            precondition(departures == (scenario == .missedTurn ? 1 : 0))
            precondition(rejoins == (scenario == .missedTurn ? 1 : 0))
            precondition(kinds.filter { $0 == .arrived }.count == 1)
            precondition(kinds.filter { $0 == .turnRight }.count == 2)
            precondition(!kinds.contains(.rerouted), "The candidate campus route must never produce verified rerouting")
            lines.append(
                "| \(scenario.rawValue) | \(session.acceptedReadings) | \(session.rejectedReadings) | \(departures) | \(rejoins) | \(kinds.filter { $0 == .turnRight || $0 == .turnLeft }.count) | \(kinds.filter { $0 == .arrived }.count) |"
            )
        }
        var session = try NavigationSession(graph: graph, route: route, source: .simulation, started: start)
        // Rapid readings cannot confirm departure, even when all are away from the route.
        let distant = MapCoordinate(
            latitude: route.coordinates[0].latitude + 0.0002, longitude: route.coordinates[0].longitude)
        for i in 0..<5 {
            let t = start.addingTimeInterval(Double(i) * 0.01)
            session.receive(NavigationPosition(time: t, coordinate: distant, accuracy: 1, source: .simulation), now: t)
        }
        precondition(!session.events.contains { $0.kind == .offRoute })
        session.checkFreshness(now: start.addingTimeInterval(20))
        precondition(session.status == .uncertain)
        precondition(NavigationCommand.parse("Where am I?") == .currentLocation)
        precondition(NavigationCommand.parse("Do not stop navigation") == nil)
        precondition(NavigationCommand.parse("repeat") == .repeatInstruction)
        var invalid = graph
        invalid.edges[0].geometry[0].latitude = 100
        precondition(!GraphValidator.validate(invalid).errors.isEmpty)
        invalid = graph
        invalid.edges[0].geometry = [graph.nodes[0].coordinate, graph.nodes[0].coordinate]
        precondition(!GraphValidator.validate(invalid).errors.isEmpty)
        invalid = graph
        invalid.edges[0].verification = .verified
        precondition(!GraphValidator.validate(invalid).errors.isEmpty)
        var preference = RoutePreferences()
        preference.crossingMultiplier = -1
        precondition(
            (try? RoutePlanner.plan(graph: graph, from: "trace-0", to: "trace-7", preferences: preference)) == nil)
        let walk = try JSONDecoder().decode(
            WalkData.self, from: Data(contentsOf: resources.appending(path: "Recordings/BoydWalkSample.json")))
        func replay(batchSize: Int) throws -> NavigationSession {
            var replay = try NavigationSession(graph: graph, route: route, source: .recording, started: walk.started)
            let inputs = ReplayInputs.positions(for: walk)
            for batch in stride(from: 0, to: inputs.count, by: batchSize) {
                for input in inputs[batch..<min(batch + batchSize, inputs.count)] {
                    replay.receive(input, now: input.time)
                }
            }
            return replay
        }
        let recorded = try replay(batchSize: 1)
        let accelerated = try replay(batchSize: 4)
        precondition(recorded.events == accelerated.events)
        let expected = ReplayInputs.expectations(for: walk)
        let evaluation = NavigationEvaluation.compare(
            expected: expected, actual: recorded.events, kinds: Set(expected.map(\.kind)))
        lines += [
            "", "## Existing measured recording", "",
            "\(walk.readings.count) GPS fixes; \(recorded.acceptedReadings) accepted, \(recorded.rejectedReadings) rejected. Final state: \(recorded.status.rawValue).",
            "", "Manual-mark comparison (±10 seconds): \(evaluation.summary).", "",
            "These marks are approximate human observations. Route geometry is unverified, so disagreement cannot be attributed to one component or used as positioning accuracy. No motion fusion or landmark recognition is evaluated.",
            "", "| Event | Seconds from start | Route progress (m) |", "| --- | ---: | ---: |",
        ]
        lines += recorded.events.map {
            "| \($0.kind.rawValue) | \(Int($0.time.timeIntervalSince(walk.started))) | \(Int($0.progressMeters)) |"
        }
        lines += [
            "", "## Additional assertions", "",
            "Passed: graph JSON/GeoJSON compatibility, malformed coordinates, zero-length geometry, missing verification evidence, invalid penalties, rapid-fix confirmation protection, stale updates, exact voice commands, and recorded 1×/4× event equivalence.",
            "",
            "The other model suite covers stair avoidance, disconnected routes, synthetic verified-junction rerouting, unknown data, early arrival rejection, turn counts, isolated outliers, and legacy recording compatibility.",
            "",
            "Physical-device speech/haptics, permission interruption, VoiceOver usability, actual route surveys, and supervised trials remain pending.",
        ]
        if let output { try lines.joined(separator: "\n").write(to: output, atomically: true, encoding: .utf8) }
        print(
            "PASS: shared normal/missed-turn/noisy scenarios, rejoin, burst protection, stale fixes, GeoJSON, recorded replay equivalence and measured-log evaluation"
        )
    }
}
